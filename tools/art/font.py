G["."] = "./././././././#"[2:]  # one column, dot on the baseline row
MARKS = {"acute": ".#/#.", "grave": "#./.#", "circ": ".#./#.#", "tilde": ".#.#/#.#."}
ACCENTED = {
    "á": ("a", "acute"), "à": ("a", "grave"), "â": ("a", "circ"), "ã": ("a", "tilde"), "é": ("e", "acute"), "ê": ("e", "circ"),
    "í": ("i", "acute"), "ó": ("o", "acute"), "ô": ("o", "circ"), "õ": ("o", "tilde"), "ú": ("u", "acute"),
    "Á": ("A", "acute"), "À": ("A", "grave"), "Â": ("A", "circ"), "Ã": ("A", "tilde"), "É": ("E", "acute"), "Ê": ("E", "circ"),
    "Í": ("I", "acute"), "Ó": ("O", "acute"), "Ô": ("O", "circ"), "Õ": ("O", "tilde"), "Ú": ("U", "acute"),
}
TOP, HEIGHT, BASE = 2, 11, 9  # two rows above the capitals for accents, two below the baseline


def cell(ch):
    """Glyph as HEIGHT rows of equal width."""
    if ch in ("ç", "Ç"):
        rows = cell("c" if ch == "ç" else "C")
        w = len(rows[0])
        rows[9] = ("." * (w - 3) + ".#.").ljust(w, ".")[:w]
        rows[10] = ("." * (w - 3) + "#..").ljust(w, ".")[:w]
        return rows
    if ch in ACCENTED:
        base, mark = ACCENTED[ch]
        m = MARKS[mark].split("/")
        rows = cell(base)
        if base == "i":  # dotless
            rows[TOP] = "." * len(rows[0])
        w = max(len(rows[0]), len(m[0]))
        rows = [r.center(w, ".") if len(r) < w else r for r in rows]
        rows = [r.replace(" ", ".") for r in rows]
        at = 0 if base.isupper() else TOP - 1
        for i, line in enumerate(m):
            pad = (w - len(line)) // 2
            rows[at + i] = "." * pad + line + "." * (w - len(line) - pad)
        return rows
    body = G[ch].split("/")
    w = max(len(r) for r in body)
    rows = ["." * w] * TOP + [r.ljust(w, ".") for r in body]
    rows += ["." * w] * (HEIGHT - len(rows))
    return rows


def png(path, w, h, pixels):
    raw = b"".join(b"\x00" + bytes(v for x in range(w) for v in ((255, 255, 255, 255) if pixels[y][x] else (0, 0, 0, 0))) for y in range(h))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    with open(path, "wb") as fh:
        fh.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def build():
    chars = list(G.keys()) + list(ACCENTED.keys()) + ["ç", "Ç"]
    W, H = 128, 128
    pixels = [[0] * W for _ in range(H)]
    x = y = 0
    lines = []
    for ch in chars:
        rows = cell(ch)
        w = len(rows[0])
        if x + w + 1 > W:
            x, y = 0, y + HEIGHT + 1
        for ry, row in enumerate(rows):
            for rx, v in enumerate(row):
                if v == "#":
                    pixels[y + ry][x + rx] = 1
        adv = w + 1 if ch != " " else 3
        lines.append(f"char id={ord(ch)} x={x} y={y} width={w} height={HEIGHT} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15")
        x += w + 1
    out = os.path.join(os.path.dirname(__file__), "..", "..", "art", "fonts")
    png(os.path.join(out, "eterra.png"), W, H, pixels)
    head = [
        'info face="Eterra" size=11 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight={HEIGHT + 1} base={BASE} scaleW={W} scaleH={H} pages=1 packed=0",
        'page id=0 file="eterra.png"',
        f"chars count={len(lines)}",
    ]
    with open(os.path.join(out, "eterra.fnt"), "w") as fh:
        fh.write("\n".join(head + lines) + "\n")


if __name__ == "__main__":
    build()
